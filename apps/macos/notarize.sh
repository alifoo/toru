#!/bin/bash
# Builds a Developer ID signed Toru.app, notarizes it, staples the ticket and writes a release zip + SHA-256.
# One-time: xcrun notarytool store-credentials toru-notary --apple-id <id> --team-id <TEAMID>
set -euo pipefail
cd "$(dirname "$0")"
: "${TORU_SIGN_IDENTITY:?Set TORU_SIGN_IDENTITY to your Developer ID Application identity}"
profile="${TORU_NOTARY_PROFILE:-toru-notary}"
# Embed the pinned Sparkle framework when it has been fetched (scripts/fetch-sparkle.sh); release builds should always have it.
sparkle="$PWD/build/Sparkle/2.10.0/Sparkle.framework"
if [ -z "${TORU_SPARKLE_FRAMEWORK:-}" ] && [ -d "$sparkle" ]; then export TORU_SPARKLE_FRAMEWORK="$sparkle"; fi
[ -n "${TORU_SPARKLE_FRAMEWORK:-}" ] || echo "warning: building without Sparkle (run scripts/fetch-sparkle.sh first)" >&2
app="$(./build.sh | tail -1)"
out="$PWD/build/release"; mkdir -p "$out"
version="$(/usr/libexec/PlistBuddy -c 'Print CFBundleShortVersionString' "$app/Contents/Info.plist")"
zip="$out/Toru-$version.zip"
rm -f "$zip"
ditto -c -k --keepParent "$app" "$zip"
xcrun notarytool submit "$zip" --keychain-profile "$profile" --wait
xcrun stapler staple "$app"
xcrun stapler validate "$app"
spctl --assess --type execute --verbose=2 "$app"
# Re-zip so the distributed archive carries the stapled ticket.
rm -f "$zip"
ditto -c -k --keepParent "$app" "$zip"
shasum -a 256 "$zip" | tee "$zip.sha256"
# EdDSA signature for the appcast (private key lives in the login Keychain; generated by Sparkle's generate_keys).
if [ -x "$PWD/build/Sparkle/2.10.0/bin/sign_update" ]; then
  "$PWD/build/Sparkle/2.10.0/bin/sign_update" "$zip" | tee "$zip.edsig"
  echo "Next: node scripts/publish-mac-release.mjs \"$zip\" --build ${TORU_BUILD:-7} --ed-signature \"$(sed -n 's/.*sparkle:edSignature=\"\([^\"]*\)\".*/\1/p' "$zip.edsig")\" --notes \"…\""
fi
